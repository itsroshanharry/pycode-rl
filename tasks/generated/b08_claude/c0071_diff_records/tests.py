import pytest
from solution import diff_records


@pytest.mark.parametrize(
    "old, new, expected",
    [
        ({"a": 1, "b": 2, "c": [1, 2]}, {"b": 2.0, "c": [1, 2], "d": None}, (["d"], ["a"], ["b"])),
        ({}, {}, ([], [], [])),
        ({"x": 1}, {"x": 1}, ([], [], [])),
        ({"x": 1}, {"x": True}, ([], [], ["x"])),
        ({"x": 0}, {"x": False}, ([], [], ["x"])),
        ({"x": 1.0}, {"x": 1}, ([], [], ["x"])),
        ({"x": None}, {"x": None}, ([], [], [])),
        ({"x": None}, {"x": 0}, ([], [], ["x"])),
        ({"x": "1"}, {"x": 1}, ([], [], ["x"])),
        ({"x": [1]}, {"x": [True]}, ([], [], ["x"])),
        ({"x": [1, [2.0]]}, {"x": [1, [2]]}, ([], [], ["x"])),
        ({"x": {"a": 1}}, {"x": {"a": 1.0}}, ([], [], ["x"])),
        ({"x": {"a": 1, "b": 2}}, {"x": {"b": 2, "a": 1}}, ([], [], [])),
        ({"x": {"a": 1}}, {"x": {"a": 1, "b": None}}, ([], [], ["x"])),
        ({"x": [1, 2]}, {"x": [2, 1]}, ([], [], ["x"])),
        ({"x": []}, {"x": {}}, ([], [], ["x"])),
        ({"x": [[], {}]}, {"x": [[], {}]}, ([], [], [])),
        ({"b": 1, "a": 1, "C": 1}, {"z": 1, "y": 1, "B": 1}, (["B", "y", "z"], ["C", "a", "b"], [])),
        ({"k": -0.0}, {"k": 0.0}, ([], [], [])),
        ({"k": 2 ** 70}, {"k": 2 ** 70}, ([], [], [])),
        ({"é": 1, "e": 1}, {"z": 2, "e": 2}, (["z"], ["é"], ["e"])),
    ],
)
def test_examples(old, new, expected):
    got = diff_records(old, new)
    assert (list(got["added"]), list(got["removed"]), list(got["changed"])) == expected
    assert set(got) == {"added", "removed", "changed"}
