def test_invalid(bad):
    with pytest.raises(ValueError):
        utc_order(["2024-01-01T00:00:00Z", bad])


_FRACS = ["", "", "5", "50", "500000000", "123456789", "1234567891", "0", "000000001", "999999"]
_BASES = [datetime(2000, 1, 1) + timedelta(days=d, seconds=s) for d, s in
          [(0, 0), (0, 1), (9000, 43210), (9000, 43211), (12345, 86399), (300, 7)]]


def _fmt(utc, frac, off_min, rng):
    local = utc + timedelta(minutes=off_min)
    s = local.strftime("%Y-%m-%dT%H:%M:%S")
    if rng.random() < 0.3:
        s = s.replace("T", "t")
    if frac:
        s += "." + frac
    if off_min == 0 and rng.random() < 0.5:
        s += rng.choice("Zz")
    else:
        sign = "-" if off_min < 0 or (off_min == 0 and rng.random() < 0.5) else "+"
        a = abs(off_min)
        s += f"{sign}{a // 60:02d}:{a % 60:02d}"
    return s


def test_random_against_oracle():
    rng = random.Random(2)
    for _ in range(300):
        items = []
        for _ in range(rng.randint(0, 12)):
            utc, frac = rng.choice(_BASES), rng.choice(_FRACS)
            off = rng.choice([0, 0, 60, -60, 330, -570, 1439, -1439, rng.randint(-1439, 1439)])
            key = (utc, Fraction(int(frac), 10 ** len(frac)) if frac else Fraction(0))
            items.append((key, _fmt(utc, frac, off, rng)))
        want = [s for _, s in sorted(items, key=lambda kv: kv[0])]
        assert list(utc_order([s for _, s in items])) == want
