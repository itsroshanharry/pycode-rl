import pytest
from solution import round_half_even


@pytest.mark.parametrize(
    "number, places, expected",
    [
        ("2.675", 2, "2.68"),
        ("1.25", 1, "1.2"),
        ("-0.5", 0, "0"),
        ("2.665", 2, "2.66"),
        ("2.5", 0, "2"),
        ("3.5", 0, "4"),
        ("-2.5", 0, "-2"),
        ("-3.5", 0, "-4"),
        ("0.125", 2, "0.12"),
        ("0.135", 2, "0.14"),
        ("1.2501", 1, "1.3"),
        ("1.2499", 1, "1.2"),
        ("-0.004", 2, "0.00"),
        ("-0.005", 2, "0.00"),
        ("-0.015", 2, "-0.02"),
        ("7", 3, "7.000"),
        ("007.50", 1, "7.5"),
        ("0", 0, "0"),
        ("-0", 2, "0.00"),
        ("9.995", 2, "10.00"),
        ("0.0000000005", 9, "0.000000000"),
        ("1.00000000000000000005", 19, "1.0000000000000000000"),
        ("123456789012345678901234567890.5", 0, "123456789012345678901234567890"),
        ("-99.95", 1, "-100.0"),
        ("12.3456", 6, "12.345600"),
    ],
)
def test_rounding(number, places, expected):
    assert round_half_even(number, places) == expected
