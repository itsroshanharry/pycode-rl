import pytest
from solution import to_e164


@pytest.mark.parametrize(
    "raw, cc, trunk, expected",
    [
        ("+44 (0)20 7946 0958", "1", "1", "+442079460958"),
        ("(415) 555-0100", "1", "1", "+14155550100"),
        ("1-415-555-0100", "1", "1", "+14155550100"),
        ("415.555.0100", "1", "1", "+14155550100"),
        ("020 7946 0958", "44", "0", "+442079460958"),
        ("(0)20 7946 0958", "44", "0", "+442079460958"),
        ("0044 20 7946 0958", "1", "1", "+442079460958"),
        ("00 1 415 555 0100", "44", "0", "+14155550100"),
        ("06 12 34 56 78", "33", "0", "+33612345678"),
        ("06 1234 5678", "39", "", "+390612345678"),
        ("8 800 555 35 35", "7", "8", "+78005553535"),
        ("+7 800 555 35 35", "44", "0", "+78005553535"),
        ("+1 (415) 555-0100", "44", "0", "+14155550100"),
        ("+49 (0)30 123456", "1", "1", "+4930123456"),
        ("+49(0)30(0)123456", "1", "1", "+4930123456"),
        ("+4930123456", "1", "1", "+4930123456"),
        ("7946 0958", "44", "0", "+4479460958"),
        ("030 1234567", "49", "0", "+49301234567"),
        ("123456789012", "999", "", "+999123456789012"),
        ("+123456789012345", "1", "1", "+123456789012345"),
        ("1234567", "1", "", "+11234567"),
    ],
)
def test_examples(raw, cc, trunk, expected):
    assert to_e164(raw, cc, trunk) == expected


@pytest.mark.parametrize(
    "raw, cc, trunk",
    [
        ("+44 20 7946 0958 ext 12", "1", "1"),
        ("555-CALL", "1", "1"),
        ("++44 20 7946 0958", "1", "1"),
        ("44+20 7946 0958", "1", "1"),
        (" +44 20 7946 0958", "1", "1"),
        ("+", "1", "1"),
        ("", "1", "1"),
        ("+0 123 456 789", "1", "1"),
        ("+1234567", "1", "1"),
        ("+1234567890123456", "1", "1"),
        ("1234567890123", "999", ""),
        ("123456", "1", ""),
        ("+４４ 20 7946 0958", "1", "1"),
        ("+44 20 7946 0958/1", "1", "1"),
        ("+44_20_7946_0958", "1", "1"),
        ("000 123 456 789", "1", "1"),
        ("0044", "1", "1"),
        ("020 7946 0958", "044", "0"),
        ("020 7946 0958", "", "0"),
        ("020 7946 0958", "1234", "0"),
        ("020 7946 0958", "44", "o"),
        ("+44\t20 7946 0958", "1", "1"),
    ],
)
def test_invalid(raw, cc, trunk):
    with pytest.raises(ValueError):
        to_e164(raw, cc, trunk)
